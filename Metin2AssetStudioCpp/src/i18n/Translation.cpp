#include "Translation.h"

Translation& Translation::instance() {
    static Translation inst;
    static bool loaded = false;
    if (!loaded) {
        loaded = true;
        const_cast<Translation&>(inst).loadEnglish();
        const_cast<Translation&>(inst).loadCzech();
    }
    return inst;
}

void Translation::setLanguage(const std::string& lang) {
    currentLang = lang;
}

std::string Translation::get(const std::string& key) const {
    auto langIt = strings.find(currentLang);
    if (langIt != strings.end()) {
        auto keyIt = langIt->second.find(key);
        if (keyIt != langIt->second.end()) return keyIt->second;
    }
    auto fallback = strings.find("en");
    if (fallback != strings.end()) {
        auto keyIt = fallback->second.find(key);
        if (keyIt != fallback->second.end()) return keyIt->second;
    }
    return key;
}

